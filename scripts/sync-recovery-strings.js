#!/usr/bin/env node
// Copies the Recovery UI strings from the Expo app so web and mobile always say
// the same thing in English and Bangla. Run after editing
// expo-connect-app/src/screens/recovery/i18n.ts:
//   node scripts/sync-recovery-strings.js
const fs = require('fs');
const path = require('path');

const source = path.resolve(__dirname, '../../expo-connect-app/src/screens/recovery/i18n.ts');
const target = path.resolve(__dirname, '../src/pages/recovery/strings.js');

const text = fs.readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
const start = text.indexOf('const en = {');
const end = text.indexOf('export const STRINGS');
if (start < 0 || end < 0) throw new Error('Could not find the string tables in i18n.ts');

const tables = text
  .slice(start, end)
  .replace('export type Strings = typeof en;\n', '')
  .replace('const bn: Strings = {', 'const bn = {')
  .trimEnd();

if (/:\s*Strings\b|\bas const\b/.test(tables)) throw new Error('Unexpected TypeScript syntax in the string tables');

const output = `// GENERATED by web/scripts/sync-recovery-strings.js from
// expo-connect-app/src/screens/recovery/i18n.ts. Do not edit by hand.
/* eslint-disable */

${tables}

export const STRINGS = { en, bn };
`;

fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, output);
console.log(`Wrote ${path.relative(process.cwd(), target)}`);
